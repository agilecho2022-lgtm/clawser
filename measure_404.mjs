import { chromium } from "playwright";
const token = process.env.DSH_RIG_TOKEN;
const browser = await chromium.launch({ headless: true, channel: "msedge" });
const context = await browser.newContext();
await context.addInitScript((v) => window.localStorage.setItem("token", v), token);
const page = await context.newPage();
const bad = [];
page.on("response", (r) => { if (r.status() >= 400) bad.push(`${r.status()} ${r.url().slice(0, 120)}`); });
await page.goto(process.argv[2], { waitUntil: "domcontentloaded" });
await page.waitForTimeout(9000);
console.log(JSON.stringify([...new Set(bad)], null, 1));
await browser.close();
